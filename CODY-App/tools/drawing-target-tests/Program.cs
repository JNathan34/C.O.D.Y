using HeyClicky;
using HeyClicky.App.Cody;
using static HeyClicky.App.Cody.CodyAccessibilityInput;
void Check(bool condition,string message){if(!condition)throw new Exception(message);Console.WriteLine("PASS: "+message);}
var viewport=new RectD(0,0,1000,800);
var root=new UiaElement(50032,viewport);
var tab=root.Add(new UiaElement(50019,new RectD(0,0,200,35),"Same title"));tab.Selected=true;
var secondTab=root.Add(new UiaElement(50019,new RectD(200,0,200,35),"Same title"));
var doc=root.Add(new UiaElement(50030,new RectD(0,40,1000,760),"Same title"));
var image=doc.Add(new UiaElement(50006,new RectD(200,180,80,80),"SocialHub icon"));
var duplicate=doc.Add(new UiaElement(50006,new RectD(200,480,80,80),"SocialHub icon"));
var text=doc.Add(new UiaElement(50020,new RectD(190,275,110,30),"SocialHub"));
var overlay=new UiaElement(50032,viewport,"Drawing overlay");
Automation=new Uia(root,overlay);
var document=await CodyDrawingTarget.Capture(1,viewport,true,()=>true);
Check(document!=null&&ReferenceEquals(document.Element,doc),"document acquisition ignores an overlaid desktop hit target");
var box=new RectD(190,170,100,100);
var first=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,null,true)],()=>true);
var anchor=first.Targets.Single().Anchor;
Check(anchor!=null&&anchor.Original==image.Bounds&&!anchor.Control,"an icon binds to its image, rather than adjacent heading text or a pressable control");
var padded=doc.Add(new UiaElement(50006,new RectD(600,150,180,220),"Speaker photograph with white padding"));
var speakerBox=new RectD(620,200,140,90);
var speaker=await CodyDrawingTarget.Read(1,document,viewport,[new(2,speakerBox,null,true)],()=>true);
var speakerAnchor=speaker.Targets.Single().Anchor;
Check(speakerAnchor!=null&&speakerAnchor.Original==padded.Bounds,"a tight ring around the speaker binds to its padded photograph");
padded.Bounds=new RectD(600,60,180,220);
var speakerMoved=await CodyDrawingTarget.Read(1,document,viewport,[new(2,speakerBox,speakerAnchor,false)],()=>true);
Check(CodyDrawingGeometry.Project(speakerBox,speakerAnchor.Original,speakerMoved.Targets.Single().Bounds.Value)==new RectD(620,110,140,90),"padded-image scrolling preserves the circled object's offset without snapping to the image centre");
Check(!CodyDrawingGeometry.FitsImage(speakerBox,new RectD(0,0,1000,800)),"a page background cannot become the speaker's anchor");
image.Bounds=new RectD(200,90,80,80);duplicate.Bounds=new RectD(200,180,80,80);
var moved=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(moved.Targets.Single().Bounds==image.Bounds&&ReferenceEquals(moved.Targets.Single().Anchor,anchor),"scroll follows the original icon even when an identical icon occupies its previous position");
tab.Selected=false;secondTab.Selected=true;
var inactive=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(inactive.Targets.Length==0&&!inactive.TabClosed,"same-title tab switch hides without deleting the original tab's anchors");
tab.Selected=true;secondTab.Selected=false;
var restored=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(restored.Targets.Single().Bounds==image.Bounds,"returning to the original tab restores the same retained image");
image.Offscreen=true;
var clipped=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(clipped.Targets.Single().Bounds==null,"an offscreen image does not leave a fixed-position ring");
image.Offscreen=false;image.Name="Replaced quiz image";await Task.Delay(270);
var replaced=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(replaced.Targets.Single().Bounds==null,"recycled image content invalidates its old annotation");
tab.Selected=false;secondTab.Selected=true;root.Children.Remove(tab);
await Task.Delay(1050); // Closed-tab scans are deliberately throttled to once/second.
var closed=await CodyDrawingTarget.Read(1,document,viewport,[new(1,box,anchor,false)],()=>true);
Check(closed.TabClosed,"closing the retained tab retires its drawings");

var legacyRoot=new LegacyFixture(10,viewport);
var legacyTab=legacyRoot.Add(new LegacyFixture(37,new RectD(0,0,200,35),"Same title"));legacyTab.Selected=true;
var legacyDoc=legacyRoot.Add(new LegacyFixture(15,new RectD(0,40,1000,760),"Page","https://example.test/one"));
var legacyImage=legacyDoc.Add(new LegacyFixture(40,new RectD(200,180,80,80),"SocialHub icon"));
var legacyDocument=new CodyDrawingLegacyTarget.Document(new(legacyRoot),new(legacyDoc),new(legacyTab),legacyDoc.Url);
var legacyFirst=CodyDrawingLegacyTarget.Read(legacyDocument,viewport,[new(4,box,null,true)],()=>true);
var legacyAnchor=legacyFirst.Targets.Single().Anchor;
Check(legacyAnchor!=null&&legacyAnchor.Original==legacyImage.Bounds,"MSAA-only image providers bind without a UIA document");
legacyImage.Bounds=new RectD(200,90,80,80);
Check(CodyDrawingLegacyTarget.Read(legacyDocument,viewport,[new(4,box,legacyAnchor,false)],()=>true).Targets.Single().Bounds==legacyImage.Bounds,"MSAA image geometry follows scrolling without rediscovering names");
legacyTab.Selected=false;
Check(CodyDrawingLegacyTarget.Read(legacyDocument,viewport,[new(4,box,legacyAnchor,false)],()=>true).Targets.Length==0,"MSAA hides a drawing when its retained tab is unselected");
legacyTab.Selected=true;legacyDoc.Url="https://example.test/two";
Check(CodyDrawingLegacyTarget.Read(legacyDocument,viewport,[new(4,box,legacyAnchor,false)],()=>true).Targets.Length==0,"MSAA navigation invalidates same-window marks before rendering unrelated content");

legacyTab.Selected=true;legacyDoc.Url=legacyDocument.Url;
LegacyFixture.FreshWrappers=true;
legacyImage.Bounds=new RectD(200,180,80,80);
var proxies=new CodyDrawingLegacyTarget.Document(new(legacyRoot.Proxy()),new(legacyDoc.Proxy()),new(legacyTab.Proxy()),legacyDoc.Url);
var proxyFrame=CodyDrawingLegacyTarget.Read(proxies,viewport,[new(5,box,null,true)],()=>true);
var proxyAnchor=proxyFrame.Targets.Single().Anchor;
Check(proxyAnchor!=null,"fresh MSAA proxy wrappers still bind through their opaque accessible identity");
legacyImage.Bounds=new RectD(200,90,80,80);
Check(CodyDrawingLegacyTarget.Read(proxies,viewport,[new(5,box,proxyAnchor,false)],()=>true).Targets.Single().Bounds==legacyImage.Bounds,"the retained proxy follows live geometry instead of storing a rectangle snapshot");
legacyDoc.IdentityEpoch++;
Check(CodyDrawingLegacyTarget.Read(proxies,viewport,[new(5,box,proxyAnchor,false)],()=>true).Targets.Single().Bounds==legacyImage.Bounds,"a retained document proxy refreshes its opaque identity after native rehosting");
legacyImage.Bounds=new RectD(200,180,80,80);legacyDoc.CoarseHit=true;
Check(CodyDrawingLegacyTarget.Read(proxies,viewport,[new(6,box,null,true)],()=>true).Targets.Single().Anchor!=null,"coarse MSAA document hits descend the owner's actual children");
legacyDoc.CoarseHit=false;legacyDoc.ChildIdHit=true;
Check(CodyDrawingLegacyTarget.Read(proxies,viewport,[new(7,box,null,true)],()=>true).Targets.Single().Anchor!=null,"negative browser child IDs resolve to their accessible object");
var otherDoc=new LegacyFixture(15,legacyDoc.Bounds,legacyDoc.Name,legacyDoc.Url);
var wrongIdentity=proxies with{Element=new(otherDoc.Proxy())};
Check(CodyDrawingLegacyTarget.Read(wrongIdentity,viewport,[new(5,box,proxyAnchor,false)],()=>true).Targets.Length==0,"matching names, URL and bounds cannot substitute a different MSAA document identity");

// Firefox may hit-test to a placeholder or its chrome instead of the page.
var firefoxRoot=new LegacyFixture(14,viewport);
firefoxRoot.Add(new LegacyFixture(15,viewport,"Placeholder"));
firefoxRoot.Add(new LegacyFixture(15,viewport,"Browser chrome","chrome://browser/content/browser.xhtml"));
var firefoxPage=firefoxRoot.Add(new LegacyFixture(15,new RectD(0,40,1000,760),"Same title","https://example.test/one"));
var firefoxImage=firefoxPage.Add(new LegacyFixture(40,new RectD(200,180,80,80),"Speaker"));
var firefoxDocument=new CodyDrawingLegacyTarget.Document(new(firefoxRoot.Proxy()),new(firefoxPage.Proxy()),null,firefoxPage.Url,Firefox:true);
var firefoxFrame=CodyDrawingLegacyTarget.Read(firefoxDocument,viewport,[new(8,box,null,true)],()=>true);
var firefoxAnchor=firefoxFrame.Targets.Single().Anchor;
Check(firefoxAnchor!=null,"Firefox placeholders and browser chrome do not invalidate a real page anchor");
firefoxImage.Bounds=new RectD(200,90,80,80);
Check(CodyDrawingLegacyTarget.Read(firefoxDocument,viewport,[new(8,box,firefoxAnchor,false)],()=>true).Targets.Single().Bounds==firefoxImage.Bounds,
    "an available Firefox page anchor follows the original element's geometry");
firefoxRoot.Children.Remove(firefoxPage);
Check(CodyDrawingLegacyTarget.Read(firefoxDocument,viewport,[new(8,box,firefoxAnchor,false)],()=>true)==null,
    "a Firefox placeholder-only frame means the content provider is unavailable");
firefoxRoot.Add(new LegacyFixture(15,firefoxPage.Bounds,firefoxPage.Name,firefoxPage.Url));
Check(CodyDrawingLegacyTarget.Read(firefoxDocument,viewport,[new(8,box,firefoxAnchor,false)],()=>true).Targets.Length==0,
    "a different Firefox content document with the same title and URL still hides the old ring");
